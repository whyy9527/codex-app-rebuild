async (page) => {
  const facts = [], errors = [], failedLocalRequests = [];
  const check = (condition, label) => { if (!condition) throw new Error(label); facts.push(label); };
  page.on('pageerror', error => errors.push(String(error)));
  page.on('response', response => { if (response.url().startsWith('http://127.0.0.1:8897/') && response.status() >= 400) failedLocalRequests.push([response.status(),response.url()]); });
  await page.setViewportSize({width:1440,height:1100});
  await page.goto('http://127.0.0.1:8897/');
  const root = page.locator('#tactical-replay');
  await root.waitFor();
  await page.waitForFunction(() => document.fonts.status === 'loaded');
  await page.locator('.tactical-map-image').evaluate(img => img.decode());
  check(await root.getAttribute('data-playing') === 'false', 'starts paused at initial positions');
  check(await root.locator('[data-marker]').count() === 10, 'ten map agents and ten matching roster entries');
  check(await root.locator('[data-tactical-agent]').count() === 10, 'both complete lineups visible');
  check((await root.textContent()).includes('非模型预测') && (await root.textContent()).includes('手工示例'), 'demo provenance visibly distinct from actual forecasts');
  check(await root.locator('img').evaluateAll(imgs => imgs.every(img => img.complete && img.naturalWidth > 0)), 'all local map and agent images loaded');
  const initial = await root.locator('[data-marker="attack-0"]').getAttribute('style');
  await root.locator('#tactical-play').click();
  await page.waitForFunction(() => Number(document.querySelector('#tactical-replay').dataset.time) > 4.3);
  await root.locator('#tactical-play').click();
  const stopped = await root.getAttribute('data-time');
  await page.waitForTimeout(350);
  check(await root.getAttribute('data-time') === stopped, 'pause freezes time');
  check(await root.locator('[data-marker="attack-0"]').getAttribute('style') !== initial, 'play moves agents along routes');
  await root.locator('#tactical-progress').focus();
  await page.keyboard.press('End');
  check(await root.locator('#tactical-time').textContent() === '00:30', 'keyboard seek reaches end');
  check(await root.locator('#tactical-phase-title').textContent() === '演示结束', 'end state has correct narration');
  await root.locator('#tactical-play').click();
  await page.waitForFunction(() => Number(document.querySelector('#tactical-replay').dataset.time) > 0.2);
  check(Number(await root.getAttribute('data-time')) < 2, 'replay restarts from zero after end');
  await root.locator('[data-tactical-map="haven"]').click();
  check(await root.getAttribute('data-map') === 'haven' && await root.getAttribute('data-time') === '0.00' && await root.getAttribute('data-playing') === 'false', 'switching map resets and pauses playback');
  await root.locator('.tactical-map-image').evaluate(img => img.decode());
  check(await root.locator('.tactical-site-labels circle').count() === 3, 'Haven has three sites on its own real map');
  await root.locator('[data-tactical-agent="defend-3"]').click();
  check(await root.locator('[data-marker="defend-3"]').getAttribute('aria-pressed') === 'true', 'selecting roster highlights corresponding map agent');
  await root.locator('#tactical-routes').uncheck();
  check(await root.locator('.tactical-path:visible').count() === 0, 'route visibility toggle hides all paths');
  await root.locator('#tactical-routes').check();
  await root.locator('#tactical-speed').selectOption('2');
  await root.locator('#tactical-play').click();
  await page.waitForTimeout(600);
  await root.locator('#tactical-play').click();
  check(Number(await root.getAttribute('data-time')) > 0.7, '2x speed advances playback');
  await root.locator('#tactical-focus').click();
  check((await root.getAttribute('class')).includes('tactical-focused'), 'focus mode opens for recording');
  await page.keyboard.press('Escape');
  check(!(await root.getAttribute('class')).includes('tactical-focused'), 'Escape exits focus mode');
  await root.locator('#tactical-reset').click();
  check(await root.getAttribute('data-time') === '0.00' && await root.getAttribute('data-playing') === 'false', 'reset restores initial stance without autoplay');
  await page.setViewportSize({width:1440,height:1400});
  await root.screenshot({path:'output/playwright/haven-desktop.png'});
  await root.locator('[data-tactical-map="ascent"]').click();
  await root.locator('#tactical-progress').evaluate(input => {input.value = '16';input.dispatchEvent(new Event('input',{bubbles:true}));});
  check(await root.locator('#tactical-phase-title').textContent() === '多线推进', 'seeking updates tactical phase and positions');
  await root.screenshot({path:'output/playwright/ascent-progress.png'});
  await root.locator('#tactical-reset').click();
  await root.locator('[data-tactical-agent="attack-0"]').click();
  await page.evaluate(() => scrollTo(0,0));
  await page.screenshot({path:'output/playwright/home-desktop.png'});
  await root.screenshot({path:'output/playwright/ascent-desktop.png'});
  for (const model of ['deepseek','doubao','mimo','codex']) {
    await page.locator(`.portrait[data-channel="${model}"]`).click();
    await root.waitFor();
    check(await root.getAttribute('data-playing') === 'false', `${model} channel retains a paused, clearly labeled independent demo`);
    check(await page.locator('.channel-meta').textContent().then(text => text.includes('独立预测')), `${model} actual forecast still available`);
  }
  await root.locator('#tactical-play').click();
  await page.locator('[data-tab="schedule"]').click();
  check(await root.count() === 0, 'leaving live tab removes tactical player');
  await page.locator('[data-tab="live"]').click();
  check(await root.getAttribute('data-playing') === 'false', 'returning to live tab does not leave a background animation');
  for (const width of [320,390,768]) {
    await page.setViewportSize({width,height:844});
    await root.scrollIntoViewIfNeeded();
    const geometry = await page.evaluate(() => ({width:innerWidth, scroll:document.documentElement.scrollWidth}));
    check(geometry.scroll <= geometry.width, `${width}px layout has no horizontal overflow`);
    check(await root.locator('[data-marker]:visible').count() === 10, `${width}px map retains ten agents`);
    if (width === 390) { await page.setViewportSize({width:390,height:1700}); await root.screenshot({path:'output/playwright/mobile-390.png'}); }
  }
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.reload();await root.waitFor();
  check(await root.getAttribute('data-playing') === 'false', 'reduced-motion preference has no map autoplay');
  await page.setViewportSize({width:1440,height:1100});
  await page.emulateMedia({reducedMotion:'no-preference'});
  check(errors.length === 0, 'zero page errors');
  check(failedLocalRequests.length === 0, 'zero failing local runtime requests');
  return {status:'pass',checks:facts.length,facts,errors,failedLocalRequests};
}
